        "1. Supervisor/author choose thermochemical convention and sign off a single consistent NH3-FINAL-1.2 core.",
        "2. Fit/check industrial Fe and promoted Ru/C kinetics within operating-pressure support; validate reactor pressure loss, thermal gradients, and hydraulics.",
        "3. Recompute scaling-consistent reachable region, 15-metal screen or clearly label pair-only sensitivity, uncertainty, alloys and every impacted manuscript figure from a single approved model.",
