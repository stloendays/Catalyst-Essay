"""Fail-closed reconciliation of frozen, thermochemical and measured-kinetics experiments.

Source outputs are generated by their independent CI jobs. Never use this as
a new canonical NH3 model or infer a measured 15-metal ordering from Fe/Ru only.
"""
from __future__ import annotations
import argparse
import csv
import json
import math
from pathlib import Path

EXPECTED_SHA = "fc259c5311744cccb82a7bc80ba4529f9bd34c61ed7933890dac70f016dce9ba"

def finite(x):
    return isinstance(x, (float, int)) and math.isfinite(float(x))

def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)

def check(thermo, swap, domain=None):
    """Integrity and cost-arithmetic checks; science outcomes are not hard-coded."""
    assert thermo["workbook_sha256"] == EXPECTED_SHA, "workbook hash drift"
    modes = thermo["results"]
    assert set(modes) == {"frozen", "NIST", "GB"}, "thermodynamic scenarios missing"
    assert modes["frozen"]["number_process_states"] == 14136
    assert len(swap["variants"]) == 8, "eight kinetics variants required"
    base = modes["frozen"]
    for metal, number in (("Fe", 15.291704676621144),
                          ("Ru", 22.03059478781101), ("Os", 25.83179725613286)):
        assert abs(base[f"{metal}_cost_USD_t"] - number) < 2e-7, f"frozen {metal} drift"
    assert abs(base["Ru_activity_parity_multiplier"] - 201.2234429878984) < 0.03
    for name, x in modes.items():
        order = x["intrinsic_order"]
        economic = x["feasible_economic_order"]
        assert len(order) == 15 and len(x["metals"]) == 15, f"{name}: incomplete metal cohort"
        assert len(set(order)) == 15 and {"Fe", "Ru", "Os"}.issubset(economic)
        assert isinstance(x["number_process_states"], int) and x["number_process_states"] > 1000
        for k in ("Fe_cost_USD_t", "Ru_cost_USD_t", "Os_cost_USD_t",
                  "Ru_activity_parity_multiplier"):
            assert finite(x[k]) and x[k] > 0, f"{name}: invalid {k}"
        expected_inversion = (order[:3] == ["Ru", "Os", "Fe"] and
                              economic[:3] == ["Fe", "Ru", "Os"])
        expected_economic = economic[:3] == ["Fe", "Ru", "Os"]
        assert x["model_inversion_Ru_Os_Fe_to_Fe_Ru_Os"] == expected_inversion, f"{name}: stale inversion flag"
        assert x["Fe_Ru_Os_order_matches_frozen"] == expected_economic, f"{name}: stale ordering flag"
        assert abs(x["Ru_minus_Fe_USD_t"] -
                   (x["Ru_cost_USD_t"] - x["Fe_cost_USD_t"])) < 1e-7, f"{name}: cost gap arithmetic"
    keys = set()
    for v in swap["variants"]:
        key = (v["states"], v["sizing"], v["scale"])
        assert key not in keys, f"duplicate kinetics scenario {key}"
        keys.add(key)
        assert v["n_states"] == modes["GB" if v["states"] == "GB" else "frozen"]["number_process_states"]
        assert finite(v["Fe"]["cost"]) and finite(v["Ru_benchmark"]["cost"])
        assert finite(v["Ru_activity_multiple_for_parity"]) and v["Ru_activity_multiple_for_parity"] > 0
        supported = v["Ru_C_supported"]
        for recovery in (0.90, 0.9555):
            for fin in (0, 12):
                item = supported[f"cashflow {fin}% r {recovery}"]
                gap = item["Ru_minus_Fe_global"]
                assert finite(gap)
                reference = item["Ru_C_global"]["cost"] - item["Fe_global"]["cost"]
                assert abs(gap - reference) < 2e-5, f"{key}: supported Ru/C gap arithmetic"
                gap_k = item["Ru_minus_Fe_KAAP"]
                reference_k = item["Ru_C_KAAP"]["cost"] - item["Fe_KAAP"]["cost"]
                assert abs(gap_k - reference_k) < 2e-5, f"{key}: KAAP gap arithmetic"
    expected_keys = {(a, b, c) for a in ("frozen", "GB")
                     for b in ("inlet", "plug") for c in ("FCAL", "source")}
    assert keys == expected_keys, "kinetics matrix incomplete or mislabelled"
    if domain is not None:
        assert domain["n_variants"] == 8 and len(domain["variants"]) == 8
        assert domain["rossetti_fit_points_n"] == 125
        assert len(domain["fugacity_convention_check"]) >= 1
        for row in domain["variants"]:
            key = (row["states"], row["sizing"], row["scale"])
            assert key in keys
            assert finite(row["Fe_global_USD_t"])
            assert finite(row["RuC_benchmark_global_USD_t"])
    return modes

def render(modes, swap, domain, out):
    out.mkdir(parents=True, exist_ok=True)
    rows = []
    for name in ("frozen", "NIST", "GB"):
        x = modes[name]
        rows.append(dict(layer="descriptor", thermochemistry=name, kinetics="Wang/S1 MKM",
                         Fe_USD_t=x["Fe_cost_USD_t"], Ru_USD_t=x["Ru_cost_USD_t"],
                         Os_USD_t=x["Os_cost_USD_t"], alpha_parity=x["Ru_activity_parity_multiplier"],
                         evidence="15-metal, no metal recovery"))
    for v in swap["variants"]:
        rows.append(dict(layer="measured_pair", thermochemistry=v["states"],
                         kinetics=f'Dyson-Simon Fe + Rossetti Ru/C; {v["sizing"]}/{v["scale"]}',
                         Fe_USD_t=v["Fe"]["cost"], Ru_USD_t=v["Ru_benchmark"]["cost"],
                         Os_USD_t="", alpha_parity=v["Ru_activity_multiple_for_parity"],
                         evidence="Fe/Ru only; Ru benchmark formulation"))
    with (out / "comparison.csv").open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
    headline = next(v for v in swap["variants"] if (v["states"], v["sizing"], v["scale"]) == ("GB", "plug", "source"))
    s = headline["Ru_C_supported"]
    thermo_inversions = [mode for mode, x in modes.items()
                         if x["model_inversion_Ru_Os_Fe_to_Fe_Ru_Os"]]
    fe_better_benchmark = sum(v["Fe"]["cost"] < v["Ru_benchmark"]["cost"]
                              for v in swap["variants"])
    ru_supported_better_at_zero = sum(v["Ru_C_supported"]["cashflow 0% r 0.9555"]["Ru_minus_Fe_global"] < 0
                                      for v in swap["variants"])
    fe_better_at_twelve = sum(v["Ru_C_supported"]["cashflow 12% r 0.9555"]["Ru_minus_Fe_global"] > 0
                              for v in swap["variants"])
    report = [
        "# NH3-FINAL-1.2 candidate | independent reconciliation",
        "",
        "**Status: exploratory, UNFROZEN. This is an evidence integration report, not an adopted 15-metal recalibration.**",
        "",
        "| Reference / kinetic basis | Fe USD/t | Ru USD/t | Os USD/t | Ru parity multiple |",
        "|---|---:|---:|---:|---:|",
    ]
    for x in rows:
        fmt = lambda y: "—" if y == "" else f"{y:.3f}"
        report.append(f'| {x["thermochemistry"]} / {x["kinetics"]} | {fmt(x["Fe_USD_t"])} | {fmt(x["Ru_USD_t"])} | {fmt(x["Os_USD_t"])} | {fmt(x["alpha_parity"])} |')
    report += [
        "",
        "## Scientific outcomes (computed, not hard-coded CI pass conditions)",
        "",
        f"- Fe/Ru/Os inversion found in {len(thermo_inversions)}/3 descriptor-based thermo-reference scenarios: {', '.join(thermo_inversions) or 'none'}.",
        f"- Fe cheaper than bulk-Ru benchmark in {fe_better_benchmark}/8 measured-kinetic sensitivities.",
        f"- Recovered supported Ru/C cheaper than Fe at 0%-financing in {ru_supported_better_at_zero}/8 scenarios; Fe cheaper at 12%/year in {fe_better_at_twelve}/8.",
        "- A physically meaningful changed ranking is a valid research outcome, not an automatic CI failure; frozen-baseline, sample coverage and numerical accounting remain mandatory checks.",
        "- Fe/Ru experimentally fitted pair has NO measured Os or other 13-metal kinetics; it cannot establish the 15-metal economic order.",
        "- The GB gas standard-state conventions match across references, but the plant process uses an ideal-gas equilibrium while the kinetic rate employs Newton-Cooper fugacities. Their high-pressure equilibrium mismatch is quantified in SOURCE_DOMAIN.md.",
        "- The frozen-state + measured-kinetics combination is an off-reference sensitivity, not the principal physical model.",
        "- No NIST+Rossetti run is claimed: an equilibrium-consistent rate law would need independently verified modification.",
        "- Ru/C and the benchmark bulk-Ru formulation are different catalyst/cost definitions; recoveries and DCF must not be merged into a pure-metal reference ordering.",
        "",
        "## Measured-pair GB/plug/source: financing test",
        "",
        "| Ru recovery | 0%/y global Ru−Fe USD/t | 12%/y global Ru−Fe USD/t |",
        "|---|---:|---:|",
    ]
    for r in (.90, .9555):
        a=s[f"cashflow 0% r {r}"]["Ru_minus_Fe_global"]
        b=s[f"cashflow 12% r {r}"]["Ru_minus_Fe_global"]
        report.append(f"| {r:.2%} | {a:+.3f} | {b:+.3f} |")
    eq = domain["fugacity_convention_check"][0]
    report += [
        "",
        "## Pressure fit-domain and equilibrium-convention diagnostics",
        "",
        f'- Optimized Ru/C pressure lies outside the 50-100 bar original fit for {domain["ru_opt_zero_finance_outside_fitted_pressure_count"]}/8 zero-finance scenarios and {domain["ru_opt_12pct_finance_outside_fitted_pressure_count"]}/8 12%-finance scenarios.',
        f'- At {eq["T_C"]:.0f} C, {eq["P_bar"]:.0f} bar: GB ideal yNH3={eq["ideal_yNH3"]:.4f}, GB+Newton-Cooper fugacity yNH3={eq["newton_cooper_yNH3"]:.4f}, a {eq["difference_percentage_points"]:+.2f} percentage-point difference.',
        f'- Reproducing {domain["rossetti_fit_points_n"]} published Ru/C source-fit measurements gives mean absolute relative error {domain["rossetti_125_fit_points_MARE"]:.1%}. These are NOT independent held-out plant data.',
        "- The fitted catalyst is 3.2 wt% Ru/C; the assumed constant rate per kg Ru at 8 wt% is additional unvalidated extrapolation.",
        "- Full pressure profile and all eight scenarios: SOURCE_DOMAIN.md and source_domain.csv in the kinetics artifact.",
        "",
        "## Publication gates (NOT satisfied by CI)",
        "",
        "1. Supervisor/author choose thermochemical convention and sign off a single consistent NH3-FINAL-1.2 core.",
        "2. Fit/check industrial Fe and promoted Ru/C kinetics within operating-pressure support; validate reactor pressure loss, thermal gradients, and hydraulics.",
        "3. Recompute scaling-consistent reachable region, 15-metal screen or clearly label pair-only sensitivity, uncertainty, alloys and every impacted manuscript figure from a single approved model.",
        "4. Apply one metal ownership/recovery/DCF convention with supported-bed inventory; audit source provenance and off-domain extrapolation.",
        "5. Keep frozen NH3-FINAL-1.1 manuscript and figures unchanged until evidence gates pass.",
        "",
    ]
    (out / "AUDIT.md").write_text("\n".join(report),encoding="utf-8")
    return report

def main():
    p=argparse.ArgumentParser()
    p.add_argument("--thermo", type=Path,required=True)
    p.add_argument("--kinetics", type=Path,required=True)
    p.add_argument("--domain", type=Path,required=True)
    p.add_argument("--out", type=Path,required=True)
    a=p.parse_args()
    domain=load(a.domain)
    modes=check(load(a.thermo),load(a.kinetics),domain)
    lines=render(modes,load(a.kinetics),domain,a.out)
    print("\n".join(lines))

if __name__ == "__main__":
    main()
